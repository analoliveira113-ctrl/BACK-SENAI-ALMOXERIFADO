drop policy if exists familias_select on public.familias;
drop policy if exists familias_insert on public.familias;
create policy familias_select on public.familias for select to anon,authenticated using (true);
create policy familias_insert on public.familias for insert to anon,authenticated with check (true);

drop policy if exists tipos_select on public.tipos;
drop policy if exists tipos_insert on public.tipos;
create policy tipos_select on public.tipos for select to anon,authenticated using (true);
create policy tipos_insert on public.tipos for insert to anon,authenticated with check (true);

drop policy if exists produtos_select on public.produtos;
create policy produtos_select on public.produtos for select to anon,authenticated using (true);

drop policy if exists historico_select on public.historico_movimentacoes;
create policy historico_select on public.historico_movimentacoes for select to anon,authenticated using (true);

grant usage on schema public to anon,authenticated;
grant select,insert on public.familias to anon,authenticated;
grant select,insert on public.tipos to anon,authenticated;
grant select on public.produtos to anon,authenticated;
grant select on public.historico_movimentacoes to anon,authenticated;

